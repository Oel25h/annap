/** Deep-map leaf strings → `string` so EL (and future locales) can diverge in copy. */
type DeepStringLeaves<T> = T extends string
  ? string
  : T extends readonly (infer U)[]
    ? ReadonlyArray<DeepStringLeaves<U>>
    : T extends object
      ? { readonly [K in keyof T]: DeepStringLeaves<T[K]> }
      : T;

/** Structure of `en` with string leaves (not English literal unions). */
export type Messages = DeepStringLeaves<typeof en>;
